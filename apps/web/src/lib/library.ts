// ПРАВИЛО (см. RULES.md, раздел «Библиотека»): новые фичи, предметы, бонусы
// и механики должны отражаться здесь одновременно с их реализацией и не теряться.
// Разделы «Предметы» и «Сеты» генерируются из каталога (ITEM_CATALOG, SETS),
// поэтому новые предметы и сеты попадают в библиотеку автоматически.
import {
  CARD_DEFS,
  ITEM_CATALOG,
  RARITY_LABEL,
  RARITY_ORDER,
  RARITY_VALUE_RANGE,
  SETS,
  cardChance,
  fmt,
} from '@auctioneer/shared';
import type { Rarity } from '@auctioneer/shared';

export type LibraryBlock =
  | { kind: 'p'; text: string }
  | { kind: 'ul'; items: string[] }
  | { kind: 'table'; head: string[]; rows: string[][] };

export interface LibraryArticle {
  id: string;
  title: string;
  blocks: LibraryBlock[];
  /** 'items' — сетка предметов указанной редкости (строится из каталога) */
  kind?: 'text' | 'items';
  rarity?: Rarity;
}

export interface LibrarySection {
  id: string;
  icon: string;
  title: string;
  articles: LibraryArticle[];
}

/** Текст статьи для поиска (название + все блоки + предметы каталога) */
export function articleSearchText(a: LibraryArticle): string {
  const parts: string[] = [a.title];
  if (a.kind === 'items' && a.rarity) {
    for (const def of ITEM_CATALOG.filter((d) => d.rarity === a.rarity)) {
      parts.push(def.name, def.desc);
    }
  }
  for (const b of a.blocks) {
    if (b.kind === 'p') parts.push(b.text);
    else if (b.kind === 'ul') parts.push(...b.items);
    else parts.push(...b.head, ...b.rows.flat());
  }
  return parts.join(' ').toLowerCase();
}

