export const ITEM_CATALOG: ItemDef[] = Object.entries(NAMES).flatMap(([rarity, entries]) =>
  entries.map((entry, i) => ({
    id: rarity + '-' + i,
    name: entry.name,
    desc: entry.desc,
    rarity: rarity as Rarity,
    value: entry.value,
    w: entry.w,
    h: entry.h,
  })),
);

/**
 * Фактические границы номиналов предметов каждой редкости.
 * Считаются автоматически по фиксированным номиналам каталога
 * (используются в библиотеке для справочной таблицы).
 */
export const RARITY_VALUE_RANGE: Record<Rarity, [number, number]> = (() => {
  const out = {} as Record<Rarity, [number, number]>;
  for (const r of RARITY_ORDER) {
    const values = ITEM_CATALOG.filter((d) => d.rarity === r).map((d) => d.value);
    out[r] = [Math.min(...values), Math.max(...values)];
  }
  return out;
})();

/** Детерминированный ГПСЧ (mulberry32) */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function randomInt(rng: () => number, min: number, max: number): number {
  return min + Math.floor(rng() * (max - min + 1));
}

export function pick<T>(rng: () => number, arr: readonly T[]): T {
  return arr[Math.floor(rng() * arr.length)];
}

export const UNIFORM_RARITY: Record<Rarity, number> = {
  white: 1, green: 1, blue: 1, purple: 1, yellow: 1, gold: 1, red: 1,
};

export const PRIZE_RARITY: Record<Rarity, number> = {
  white: 26, green: 24, blue: 19, purple: 13, yellow: 6, gold: 8, red: 4,
};

export function pickRarity(rng: () => number, weights: Record<Rarity, number>): Rarity {
  const entries = Object.entries(weights) as [Rarity, number][];
  const total = entries.reduce((s, [, w]) => s + w, 0);
  let r = rng() * total;
  for (const [rarity, w] of entries) {
    r -= w;
    if (r < 0) return rarity;
  }
  return entries[entries.length - 1][0];
}

/** Экземпляр предмета по определению каталога (номинал и размер фиксированы) */
function instanceFromDef(def: ItemDef): ItemInstance {
  return {
    id: crypto.randomUUID(),
    defId: def.id,
    name: def.name,
    rarity: def.rarity,
    value: def.value,
    w: def.w,
    h: def.h,
  };
}

/**
 * Случайный предмет: редкость выбирается по весам, внутри редкости — случайный
 * предмет каталога. Номинал и размер берутся из каталога и не меняются.
 */
export function generateItem(
  rng: () => number,
  opts: { rarityWeights?: Record<Rarity, number> } = {},
): ItemInstance {
  const rarity = pickRarity(rng, opts.rarityWeights ?? UNIFORM_RARITY);
  const pool = ITEM_CATALOG.filter((d) => d.rarity === rarity);
  const def = pick(rng, pool);
  return instanceFromDef(def);
}

/**
 * Стартовый набор нового игрока: случайные предметы суммарной
 * стоимостью в STARTER_PACK_MIN..STARTER_PACK_MAX (~300 000).
 * Предметы, которые не помещаются в целевой диапазон, пропускаются.
 */
export function generateStarterPack(rng: () => number): ItemInstance[] {
  for (let attempt = 0; attempt < 5; attempt++) {
    const pack: ItemInstance[] = [];
    let total = 0;
    let guard = 0;
    while (total < STARTER_PACK_MIN && pack.length < 12 && guard++ < 400) {
      const item = generateItem(rng);
      if (total + item.value > STARTER_PACK_MAX) continue; // не помещается в диапазон — пропускаем
      pack.push(item);
      total += item.value;
    }
    if (total >= STARTER_PACK_MIN && total <= STARTER_PACK_MAX) return pack;
  }
  // Гарантированный фолбэк: жадно добираем самыми дорогими подходящими предметами
  const pack: ItemInstance[] = [];
  let total = 0;
  const candidates = ITEM_CATALOG
    .filter((d) => d.value <= STARTER_PACK_MAX)
    .sort((a, b) => b.value - a.value);
  let guard = 0;
  while (total < STARTER_PACK_MIN && guard++ < 1000) {
    const def = candidates.find((d) => total + d.value <= STARTER_PACK_MAX);
    if (!def) break;
    pack.push(instanceFromDef(def));
    total += def.value;
  }
  return pack;
}

export function itemsTotal(items: readonly { value: number }[]): number {
  return items.reduce((s, i) => s + i.value, 0);
}

/** Отформатировать число как игровую валюту (без неразрывных пробелов) */
export function fmt(n: number): string {
  return n.toLocaleString('ru-RU').replace(new RegExp(String.fromCharCode(160) + '|' + String.fromCharCode(8239), 'g'), ' ');
}
